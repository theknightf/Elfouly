import type { Question } from '../engine/types';
import { categoryLabel } from '../engine/categories';

interface McqEntry {
  prompt: string;
  correct: string;
  wrong: [string, string, string];
}

function buildQuestions(
  prefix: string,
  category: string,
  entries: McqEntry[]
): Question[] {
  return entries.map((entry, index) => {
    // Rotate the correct answer through the four positions so the UI never
    // gives the answer away by always placing it first.
    const correctIndex = (index * 3 + 1) % 4;
    const options = [...entry.wrong];
    options.splice(correctIndex, 0, entry.correct);

    return {
      id: `${prefix}:${index + 1}`,
      prompt: entry.prompt,
      options,
      correctIndex,
      category,
      categoryLabel: categoryLabel(category)
    };
  });
}

