let gkIndex = 0;

// Transform or replace all computer_science and tourism_hospitality items
const updated = questions.map((item, idx) => {
  const cat = item.category;
  if (cat === 'computer_science' || cat === 'programming' || cat === 'tourism_hospitality' || cat === 'tourism_and_hospitality') {
    const gk = GK_QUESTIONS[gkIndex % GK_QUESTIONS.length];
    gkIndex++;

    const newQText = item.mode === 'one_two_bank' 
      ? gk.q 
      : item.mode === 'hat_fi_qoraybi'
      ? gk.q
      : item.mode === 'edini_fi_seri'
      ? (item.target_word || gk.a)
      : (item.question_text || gk.q);

    const newAnswer = item.mode === 'one_two_bank'
      ? gk.a
      : item.mode === 'hat_fi_qoraybi'
      ? gk.a
      : (item.correct_answer || gk.a);

    const hash = crypto.createHash('md5').update(`${item.mode}_general_knowledge_${newQText}`).digest('hex');

    return {
      ...item,
      category: 'general_knowledge',
      question_text: newQText,
      correct_answer: newAnswer,
      content_hash: hash,
      is_post_2010_football: false
    };
  }
  return item;
});

// Check categories distribution
const catCounts = {};
updated.forEach(q => {
  catCounts[q.category] = (catCounts[q.category] || 0) + 1;
});

console.log('Updated category distribution:', catCounts);
fs.writeFileSync(bankPath, JSON.stringify(updated, null, 2), 'utf-8');
console.log('Successfully written updated questions_bank.json!');
